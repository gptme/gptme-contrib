"""The post-checkout hook must not let an installer wipe the main checkout's node_modules.

The hook used to symlink the whole ``node_modules`` directory into every linked
worktree. ``npm ci`` removes ``node_modules`` before rebuilding it, and through a
directory symlink that emptied the *main checkout's* dependencies (aw-webui
2026-09-25, gptme 2026-10-02). The worktree now gets a real directory of
per-entry symlinks, so removing it deletes only links.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HOOK = ROOT / "dotfiles" / ".config" / "git" / "hooks" / "post-checkout"


def _git(repo: Path, *args: str) -> None:
    # hooksPath off: Bob's global core.hooksPath would run the real hook set on
    # these fixture repos (and symlink node_modules before the test does).
    subprocess.run(
        ["git", "-C", str(repo), "-c", "core.hooksPath=/dev/null", *args],
        check=True,
        capture_output=True,
    )


def _setup(tmp_path: Path) -> tuple[Path, Path]:
    main = tmp_path / "main"
    main.mkdir()
    subprocess.run(["git", "init", "-q", str(main)], check=True)
    _git(main, "config", "user.email", "t@t")
    _git(main, "config", "user.name", "t")
    nm = main / "node_modules"
    (nm / "pkg").mkdir(parents=True)
    (nm / "pkg" / "index.js").write_text("module.exports = 1\n")
    (nm / "@scope" / "a").mkdir(parents=True)
    (nm / "@scope" / "a" / "index.js").write_text("module.exports = 2\n")
    (nm / ".bin").mkdir()
    (nm / ".bin" / "tool").write_text("#!/bin/sh\n")
    (nm / ".cache").mkdir()
    (nm / ".cache" / "blob").write_text("cached\n")
    (nm / ".package-lock.json").write_text("{}\n")
    (main / "README").write_text("x\n")
    _git(main, "add", "README")
    _git(main, "commit", "-q", "-m", "init")
    wt = tmp_path / "wt"
    _git(main, "worktree", "add", "-q", "--detach", str(wt), "HEAD")
    assert not (wt / "node_modules").exists()
    return main, wt


def _run_hook(wt: Path) -> None:
    subprocess.run(
        ["bash", str(HOOK), "0" * 40, "1" * 40, "1"],
        cwd=wt,
        check=True,
        capture_output=True,
    )


def test_worktree_gets_real_dir_of_entry_symlinks(tmp_path: Path) -> None:
    main, wt = _setup(tmp_path)
    _run_hook(wt)

    nm = wt / "node_modules"
    assert nm.is_dir() and not nm.is_symlink()
    for entry in ("pkg", "@scope", ".bin", ".package-lock.json"):
        assert (nm / entry).is_symlink(), entry
    assert (nm / "pkg" / "index.js").read_text() == "module.exports = 1\n"
    assert (nm / "@scope" / "a" / "index.js").exists()
    # Tool caches stay worktree-local instead of racing in the main checkout.
    assert not (nm / ".cache").exists()


def test_removing_worktree_node_modules_leaves_main_intact(tmp_path: Path) -> None:
    """What `npm ci` does first: rm -rf node_modules. It must not reach the donor."""
    main, wt = _setup(tmp_path)
    _run_hook(wt)

    shutil.rmtree(wt / "node_modules")

    donor = main / "node_modules"
    assert (donor / "pkg" / "index.js").read_text() == "module.exports = 1\n"
    assert (donor / "@scope" / "a" / "index.js").exists()
    assert (donor / ".bin" / "tool").exists()
    assert (donor / ".cache" / "blob").exists()


def test_existing_real_node_modules_is_left_alone(tmp_path: Path) -> None:
    main, wt = _setup(tmp_path)
    (wt / "node_modules").mkdir()
    (wt / "node_modules" / "mine").write_text("own install\n")

    _run_hook(wt)

    assert sorted(p.name for p in (wt / "node_modules").iterdir()) == ["mine"]


def test_broken_legacy_symlink_is_rebuilt(tmp_path: Path) -> None:
    main, wt = _setup(tmp_path)
    (wt / "node_modules").symlink_to(tmp_path / "gone" / "node_modules")

    _run_hook(wt)

    nm = wt / "node_modules"
    assert nm.is_dir() and not nm.is_symlink()
    assert (nm / "pkg" / "index.js").exists()
